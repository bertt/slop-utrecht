// Generate js/subway-geodata.js from the cached MTA entrance survey.
// Usage: node tools/build-subway-entrances.mjs [--fetch]
import fs from 'node:fs';
import { gzipSync } from 'node:zlib';
import { toWorld } from './geo-base.mjs';
import { GEO } from '../js/nyc-geodata.js';

const SOURCE = 'https://data.ny.gov/resource/i9wp-a4ja.json';
const CACHE = new URL('data/mta_subway_entrances.json', import.meta.url);
const OUTPUT = new URL('../js/subway-geodata.js', import.meta.url);
const LIMIT = 5000;
const q = (value) => Math.round(value * 10) / 10;

function validate(rows) {
  if (!Array.isArray(rows) || rows.length === 0 || rows.length >= LIMIT) {
    throw new Error('Expected a complete, nonempty Manhattan entrance survey.');
  }
  for (const row of rows) {
    const lat = Number(row.entrance_latitude);
    const lon = Number(row.entrance_longitude);
    if (row.borough !== 'M' || !row.stop_name || !row.complex_id || !row.station_id ||
      !row.daytime_routes || !row.entrance_type ||
      !['YES', 'NO'].includes(row.entry_allowed) || !['YES', 'NO'].includes(row.exit_allowed) ||
      !(lat > 40 && lat < 41 && lon > -75 && lon < -73)) {
      throw new Error(`Invalid MTA entrance record: ${JSON.stringify(row)}`);
    }
  }
}

let cache;
if (process.argv.includes('--fetch')) {
  const url = new URL(SOURCE);
  url.searchParams.set('$where', "borough = 'M'");
  url.searchParams.set('$limit', String(LIMIT));
  url.searchParams.set('$order', 'complex_id,station_id,entrance_latitude,entrance_longitude');
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`MTA download failed: HTTP ${response.status}`);
  const rows = await response.json();
  validate(rows);
  cache = { source: SOURCE, retrieved: new Date().toISOString().slice(0, 10), rows };
  fs.writeFileSync(CACHE, JSON.stringify(cache) + '\n');
} else {
  cache = JSON.parse(fs.readFileSync(CACHE, 'utf8'));
  validate(cache.rows);
}

function onIsland(x, z) {
  if (z < GEO.frame.cutZ) return false;
  const ring = GEO.manhattan;
  let inside = false;
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    const ax = ring[j], az = ring[j + 1];
    const bx = ring[i], bz = ring[i + 1];
    if ((az > z) !== (bz > z) && x < ax + (z - az) * (bx - ax) / (bz - az)) inside = !inside;
  }
  return inside;
}

const stairs = cache.rows.filter((row) => row.entrance_type === 'Stair');
const entrances = stairs.filter((row) => row.entry_allowed === 'YES' || row.exit_allowed === 'YES')
  .map((row) => ({
    point: toWorld(Number(row.entrance_longitude), Number(row.entrance_latitude)),
    complex: row.complex_id,
    name: row.stop_name,
    routes: row.daytime_routes.trim().split(/\s+/).sort().join(' ')
  }))
  .filter(({ point: [x, z] }) => onIsland(x, z))
  .sort((a, b) => Number(a.complex) - Number(b.complex) || a.point[1] - b.point[1] || a.point[0] - b.point[0]);

const stations = [];
const stationIndices = new Map();
const points = new Map();
for (const { point: [x, z], name, routes } of entrances) {
  const key = `${q(x)},${q(z)}`;
  if (points.has(key)) continue;
  // Some source complex IDs are inconsistent; keep each entrance's own station name and routes.
  const stationKey = `${name}|${routes}`;
  if (!stationIndices.has(stationKey)) {
    stationIndices.set(stationKey, stations.length);
    stations.push([name, routes]);
  }
  points.set(key, [q(x), q(z), stationIndices.get(stationKey)]);
}

const output = `// Generated by tools/build-subway-entrances.mjs; do not edit.
// MTA Subway Entrances and Exits: 2024 — ${SOURCE}
// Snapshot: ${cache.retrieved}. Active outdoor stairs within the detailed Manhattan map.
// Stations: [name, routes]. Entrances: [x, z, stationIndex], metres in the city frame.
export const SUBWAY_STATIONS = ${JSON.stringify(stations)};
export const SUBWAY_ENTRANCES = ${JSON.stringify([...points.values()])};
`;
fs.writeFileSync(OUTPUT, output);
console.log(`[subway] ${cache.rows.length} Manhattan records, ${stairs.length} stairs, ${entrances.length} active stairs in map`);
console.log(`[subway] ${points.size} entrances, ${stations.length} station/route labels (${entrances.length - points.size} duplicates removed)`);
console.log(`[subway] ${Buffer.byteLength(output)} bytes; ${gzipSync(output).length} bytes gzip`);
