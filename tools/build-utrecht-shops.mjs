// Builds js/utrecht-shops.js: named shops, cafés, restaurants, banks and pharmacies from OpenStreetMap
// (© OpenStreetMap contributors, ODbL), projected into the Domtoren-centred metre frame of utrecht-geodata.js.
// usage: node tools/build-utrecht-shops.mjs [overpass-response.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { UTRECHT_DATA } from '../js/utrecht-geodata.js';

const { lonLatAffine: A, bounds: [minX, minZ, maxX, maxZ], geographicBounds: [s, w, n, e] } = UTRECHT_DATA.meta;
const query = `[out:json][timeout:120];(nw["shop"]["name"](${s},${w},${n},${e});` +
  `nw["amenity"~"^(cafe|restaurant|fast_food|bank|pharmacy)$"]["name"](${s},${w},${n},${e}););out center tags;`;
const ENDPOINTS = ['https://overpass-api.de/api/interpreter', 'https://lz4.overpass-api.de/api/interpreter', 'https://z.overpass-api.de/api/interpreter'];

async function fetchOverpass() {
  for (let attempt = 0; attempt < 6; attempt++) {
    for (const url of ENDPOINTS) {
      try {
        const res = await fetch(url, {
          method: 'POST',
          headers: { 'User-Agent': 'slop-utrecht/1.0 (github.com/bertt/slop-utrecht)', 'Content-Type': 'application/x-www-form-urlencoded' },
          body: 'data=' + encodeURIComponent(query)
        });
        if (res.ok) return await res.json();
      } catch { /* try the next endpoint */ }
    }
    await new Promise((r) => setTimeout(r, 10000 * (attempt + 1)));
  }
  throw new Error('Overpass unavailable');
}

const input = process.argv[2];
const data = input ? JSON.parse(readFileSync(input, 'utf8')) : await fetchOverpass();

const project = (lon, lat) => {
  const a = lon - A.lon0, b = lat - A.lat0;
  return [A.x[0] + A.x[1] * a + A.x[2] * b, A.z[0] + A.z[1] * a + A.z[2] * b];
};
const kindOf = (t) => t.shop ? 'shop' : t.amenity;
const out = [];
for (const el of data.elements) {
  const lon = el.lon ?? el.center?.lon, lat = el.lat ?? el.center?.lat;
  if (lon == null || !el.tags?.name) continue;
  const [x, z] = project(lon, lat);
  if (x < minX || x > maxX || z < minZ || z > maxZ) continue;
  const name = el.tags.name.trim();
  if (out.some((o) => o[0] === name && Math.hypot(o[1] - x, o[2] - z) < 4)) continue;
  out.push([name, Math.round(x * 10) / 10, Math.round(z * 10) / 10, kindOf(el.tags)]);
}
out.sort((a, b) => a[1] - b[1] || a[2] - b[2]);

writeFileSync(new URL('../js/utrecht-shops.js', import.meta.url),
  '// Generated by tools/build-utrecht-shops.mjs from OpenStreetMap (© OpenStreetMap contributors, ODbL).\n' +
  '// [name, x, z, kind] in the Domtoren-centred metre frame (x east, z south).\n' +
  'export const UTRECHT_SHOPS = [\n' + out.map((o) => '  ' + JSON.stringify(o)).join(',\n') + '\n];\n');
console.log(`${out.length} shops written`);
