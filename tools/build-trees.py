#!/usr/bin/env python3
"""Generate js/tree-geodata.js and its gzip asset from NYC Parks Forestry Tree Points.

python3 tools/build-trees.py /tmp/nyc-trees.json

The JSON snapshot stays outside the repository. It must contain location, tpstructure
and tpcondition columns from https://data.cityofnewyork.us/resource/hn5i-inap.json.
Only full, living trees inside the detailed Manhattan map are retained.
"""

import argparse
import gzip
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SOURCE = 'https://data.cityofnewyork.us/resource/hn5i-inap.json'
PRECISION = 0.5


def load_frame():
    # Read the existing projection so tree positions agree with roads and buildings.
    script = """
console.log = () => {};
const { toWorld } = await import('./tools/geo-base.mjs');
const { GEO } = await import('./js/nyc-geodata.js');
const lon = -73.98185, lat = 40.75318;
process.stdout.write(JSON.stringify({ lon, lat, origin: toWorld(lon, lat),
  east: toWorld(lon + 1, lat), north: toWorld(lon, lat + 1), island: GEO.manhattan }));
"""
    frame = json.loads(subprocess.check_output(
        ['node', '--no-warnings', '--input-type=module', '-e', script], cwd=ROOT))
    ox, oz = frame['origin']
    ex, ez = frame['east'][0] - ox, frame['east'][1] - oz
    nx, nz = frame['north'][0] - ox, frame['north'][1] - oz

    def project(lon, lat):
        lon, lat = lon - frame['lon'], lat - frame['lat']
        return ox + lon * ex + lat * nx, oz + lon * ez + lat * nz

    island = list(zip(frame['island'][::2], frame['island'][1::2]))
    return project, island


def inside(x, z, ring):
    hit = False
    ax, az = ring[-1]
    for bx, bz in ring:
        if (az > z) != (bz > z) and x < (bx - ax) * (z - az) / (bz - az) + ax:
            hit = not hit
        ax, az = bx, bz
    return hit


def prepare(rows):
    project, island = load_frame()
    min_x, max_x = min(p[0] for p in island), max(p[0] for p in island)
    min_z, max_z = min(p[1] for p in island), max(p[1] for p in island)
    points = set()
    for row in rows:
        if row.get('tpstructure') != 'Full' or row.get('tpcondition') == 'Dead':
            continue
        coordinates = (row.get('location') or {}).get('coordinates')
        if not coordinates or len(coordinates) != 2:
            continue
        lon, lat = map(float, coordinates)
        if not math.isfinite(lon) or not math.isfinite(lat):
            continue
        x, z = project(lon, lat)
        if min_x <= x <= max_x and min_z <= z <= max_z and inside(x, z, island):
            points.add((round(x / PRECISION), round(z / PRECISION)))
    if not points:
        raise ValueError('No living trees inside the detailed Manhattan map.')
    ox, oz = min(p[0] for p in points), min(p[1] for p in points)
    bits = max(max(x - ox, z - oz) for x, z in points).bit_length()

    def morton(point):
        x, z = point[0] - ox, point[1] - oz
        return sum(((x >> i) & 1) << (2 * i) | ((z >> i) & 1) << (2 * i + 1) for i in range(bits))

    return sorted(points, key=morton)


def pack(points):
    xs, zs = bytearray(), bytearray()

    def delta(data, value):
        value = value * 2 if value >= 0 else -value * 2 - 1
        while value > 127:
            data.append((value & 127) | 128)
            value >>= 7
        data.append(value)

    x = z = 0
    for px, pz in points:
        delta(xs, px - x)
        delta(zs, pz - z)
        x, z = px, pz
    # NYT1: count and X-stream length, followed by X/Z delta varints on a 0.5 m grid.
    return struct.pack('<4sII', b'NYT1', len(points), len(xs)) + xs + zs


def module(count, asset, digest):
    return f'''// Generated by tools/build-trees.py; do not edit.
// NYC Parks Forestry Tree Points: {SOURCE}
// Snapshot SHA-256: {digest}
// {count:,} unique living tree locations, quantized to 0.5 m.
const response = await fetch(new URL('./{asset}', import.meta.url));
if (!response.ok) throw new Error(`Tree data request failed: ${{response.status}}`);
// Servers that send .gz files as Content-Encoding: gzip hand over bytes the browser has already inflated
const body = new Uint8Array(await response.arrayBuffer());
const data = body[0] === 0x1f && body[1] === 0x8b
  ? new Uint8Array(await new Response(new Response(body).body.pipeThrough(new DecompressionStream('gzip'))).arrayBuffer())
  : body;
const invalidData = () => new Error('Invalid tree data.');
if (data.length < 12) throw invalidData();
const header = new DataView(data.buffer);
const count = header.getUint32(4, true), zStart = 12 + header.getUint32(8, true);
if (header.getUint32(0, true) !== 0x3154594e || count === 0 ||
  count > zStart - 12 || count > data.length - zStart) throw invalidData();

// NYT1 stores separate X/Z streams of signed coordinate deltas on a 0.5 m grid.
function stream(start, end) {{
  let cursor = start;
  return {{
    delta() {{
      let value = 0, shift = 0, byte;
      do {{
        if (cursor >= end || shift >= 28) throw invalidData();
        byte = data[cursor++];
        value |= (byte & 127) << shift;
        shift += 7;
      }} while (byte & 128);
      return (value >>> 1) ^ -(value & 1);
    }},
    done: () => cursor === end
  }};
}}
const xs = stream(12, zStart), zs = stream(zStart, data.length);
export const REAL_TREES = new Float32Array(count * 2);
let x = 0, z = 0;
for (let i = 0; i < REAL_TREES.length; i += 2) {{
  x += xs.delta(); z += zs.delta();
  REAL_TREES[i] = x * 0.5;
  REAL_TREES[i + 1] = z * 0.5;
}}
if (!xs.done() || !zs.done()) throw invalidData();
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'js/tree-geodata.js')
    args = parser.parse_args()
    source = args.source.read_bytes()
    rows = json.loads(source)
    if not isinstance(rows, list) or not rows:
        raise ValueError('Expected a nonempty JSON array of tree locations.')
    trees = prepare(rows)
    asset = args.output.with_suffix('.bin.gz')
    compressed = gzip.compress(pack(trees), compresslevel=6, mtime=0)
    asset.write_bytes(compressed)
    output = module(len(trees), asset.name, hashlib.sha256(source).hexdigest())
    args.output.write_text(output)
    print(f'[trees] {len(trees)} unique locations; {len(compressed)} bytes gzip data; {len(output.encode())} bytes JavaScript')


if __name__ == '__main__':
    main()
